resolve_path() {
  local path=${1:-}
  [ -n "${path}" ] || return 0
  if [[ "${path}" = /* ]]; then
    printf '%s\n' "${path}"
  else
    printf '%s/%s\n' "${REPO_DIR}" "${path}"
  fi
}

bool_true() {
  case "${1:-0}" in
    1|true|TRUE|yes|YES|on|ON) return 0 ;;
    *) return 1 ;;
  esac
}

quote_exports() {
  local key
  for key in "$@"; do
    printf '%s=%q\n' "${key}" "${!key-}"
  done
}

source_env_file() {
  local path=$1
  local label=${2:-profile}
  path=$(resolve_path "${path}")
  [ -f "${path}" ] || { echo "Missing ${label}: ${path}" >&2; exit 1; }
  set -a
  # shellcheck disable=SC1090
  source "${path}"
  set +a
}

profile_keys() {
  local path
  for path in "$@"; do
    [ -n "${path}" ] || continue
    path=$(resolve_path "${path}")
    [ -f "${path}" ] || continue
    sed -nE 's/^([A-Za-z_][A-Za-z0-9_]*)=.*/\1/p' "${path}"
  done
}

write_resolved_profile() {
  local target=$1
  shift
  local profile_paths=("$@")
  shift $#
  mkdir -p "$(dirname "${target}")"
  {
    printf '# Generated by %s\n' "$(basename "$0")"
    profile_keys "${profile_paths[@]}" | awk 'NF && !seen[$0]++' | while read -r key; do
      printf '%s=%q\n' "${key}" "${!key-}"
    done
  } > "${target}"
}

write_named_env() {
  local target=$1
  shift
  mkdir -p "$(dirname "${target}")"
  {
    printf '# Generated by %s\n' "$(basename "$0")"
    quote_exports "$@"
  } > "${target}"
}

read_nodes_from() {
  local nodes_file=${1:-}
  local selector=${2:-}
  if [ -z "${nodes_file}" ]; then
    echo "this"
  elif [ -z "${selector}" ]; then
    awk 'NF && $1 !~ /^#/ {print $1}' "${nodes_file}"
  else
    awk -v sel="${selector}" '
      BEGIN {
        n = split(sel, parts, ",")
        for (i = 1; i <= n; i++) wanted[parts[i]] = 1
        idx = 0
      }
      NF && $1 !~ /^#/ {
        if (idx in wanted) print $1
        idx++
      }
    ' "${nodes_file}"
  fi
}

