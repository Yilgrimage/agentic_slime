wait_http() {
  local url=$1
  local py=${SLIME_PYTHON}
  if [ "${DRY_RUN}" = "1" ]; then
    echo "+ wait_http ${url}"
    return 0
  fi
  for _ in $(seq 1 300); do
    if "${py}" - <<PY 2>/dev/null
import json, urllib.request
data = json.loads(urllib.request.urlopen("${url}", timeout=2).read().decode())
raise SystemExit(0 if data.get("ok") else 1)
PY
    then
      echo "ready: ${url}"
      return 0
    fi
    sleep 2
  done
  echo "Timed out waiting for ${url}" >&2
  return 1
}

remote_wait_http() {
  local host=$1
  local url=$2
  local cmd
  cmd=$(cat <<EOF
${SLIME_PYTHON@Q} - <<'PY'
import json, urllib.request, time, sys
url = ${url@Q}
for _ in range(300):
    try:
        data = json.loads(urllib.request.urlopen(url, timeout=2).read().decode())
        if data.get("ok"):
            print("ready", url)
            sys.exit(0)
    except Exception:
        pass
    time.sleep(2)
sys.exit(1)
PY
EOF
)
  echo "Waiting ${host} ${url}"
  remote_query "${host}" "${cmd}"
}

ray_alive_nodes() {
  timeout 20 "${SLIME_PYTHON}" - <<PY
import ray
try:
    ray.init(address="127.0.0.1:${RAY_PORT}", ignore_reinit_error=True, logging_level="ERROR")
    print(sum(1 for n in ray.nodes() if n.get("Alive")))
finally:
    ray.shutdown()
PY
}

