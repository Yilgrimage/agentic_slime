start_train_driver() {
  local router_url=$1
  local driver status_file train_log wrapper bench_log
  driver=$(write_train_driver "${router_url}")
  status_file="${LOG_DIR}/${ENV_NAME}_train_status.env"
  train_log="${LOG_DIR}/${ENV_NAME}_train.log"
  wrapper="${LOG_DIR}/${ENV_NAME}_train_tmux.sh"
  bench_log="${LOG_DIR}/bench_on_train_exit.log"
  {
    printf '#!/usr/bin/env bash\nset +e\n'
    printf 'DRIVER=%q\n' "${driver}"
    printf 'TRAIN_LOG=%q\n' "${train_log}"
    printf 'STATUS_FILE=%q\n' "${status_file}"
    printf 'BENCH_LOG=%q\n' "${bench_log}"
    printf 'BENCH_ON_TRAIN_EXIT=%q\n' "${BENCH_ON_TRAIN_EXIT}"
    printf 'MLF_NAS_ROOT=%q\n' "${MLF_NAS_ROOT}"
    printf 'RUN_BENCH=%q\n' "${MLF_NAS_ROOT}/bash/run_bench.sh"
    printf 'NODES_FILE=%q\n' "${NODES_FILE}"
    printf 'NODE_INDICES=%q\n' "${NODE_INDICES}"
    printf 'SSH_USER=%q\n' "${SSH_USER}"
    printf 'SSH_PORT=%q\n' "${SSH_PORT}"
    printf 'SSH_KEY=%q\n' "${SSH_KEY}"
    printf 'SSH_IPV6=%q\n' "${SSH_IPV6}"
    printf 'SSH_JUMP=%q\n' "${SSH_JUMP}"
    printf 'BENCH_ON_EXIT_SUPPRESS_FILE=%q\n' "${BENCH_ON_EXIT_SUPPRESS_FILE}"
    cat <<'EOF'
finish() {
  local code=$?
  local now suppress_until skip_bench=0
  printf "exit_code=%s\nend_time=%s\n" "${code}" "$(date -Is)" > "${STATUS_FILE}"
  if [ -n "${BENCH_ON_EXIT_SUPPRESS_FILE}" ] && [ -f "${BENCH_ON_EXIT_SUPPRESS_FILE}" ]; then
    now=$(date +%s)
    suppress_until=$(cat "${BENCH_ON_EXIT_SUPPRESS_FILE}" 2>/dev/null || echo 0)
    if [ "${suppress_until:-0}" -gt "${now}" ] 2>/dev/null; then
      skip_bench=1
      printf "[%s] train exited code=%s; skip run_bench because reset suppression is active until %s\n" \
        "$(date -Is)" "${code}" "${suppress_until}" >> "${BENCH_LOG}" 2>&1 || true
    fi
  fi
  if [ "${BENCH_ON_TRAIN_EXIT}" = "1" ] && [ "${skip_bench}" != "1" ] && [ -n "${NODES_FILE}" ] && [ -f "${RUN_BENCH}" ]; then
    {
      echo "[$(date -Is)] train exited code=${code}; running run_bench start --nodes ${NODES_FILE} --node ${NODE_INDICES}"
      bench_args=(start --nodes "${NODES_FILE}")
      [ -z "${NODE_INDICES}" ] || bench_args+=(--node "${NODE_INDICES}")
      MLF_NAS_ROOT="${MLF_NAS_ROOT}" SSH_USER="${SSH_USER}" SSH_PORT="${SSH_PORT}" \
        SSH_KEY="${SSH_KEY}" SSH_IPV6="${SSH_IPV6}" SSH_JUMP="${SSH_JUMP}" \
        bash "${RUN_BENCH}" "${bench_args[@]}"
    } >> "${BENCH_LOG}" 2>&1 || true
  fi
  exit "${code}"
}

trap finish EXIT
trap 'exit 130' INT
trap 'exit 143' TERM

printf "state=running\nstart_time=%s\n" "$(date -Is)" > "${STATUS_FILE}"
bash "${DRIVER}" > "${TRAIN_LOG}" 2>&1
EOF
    printf 'code=$?\n'
    printf 'exit "$code"\n'
  } > "${wrapper}"
  chmod +x "${wrapper}"
  tmux_start_local "mlf_${ENV_NAME}_train" "bash ${wrapper}"
  echo "Training submitted in tmux: mlf_${ENV_NAME}_train"
  echo "Training log: ${train_log}"
  echo "Train status: ${status_file}"
}

run_worker() {
  source_env_file "${RESOLVED_CONFIG}" resolved
  start_env_server
  wait_http "http://127.0.0.1:${ENV_PORT}/health"
  start_ray_worker "${HEAD_ADDRESS:?worker needs --head-address}"
}

run_head() {
  source_env_file "${RESOLVED_CONFIG}" resolved
  mkdir -p "${LOG_DIR}"
  HEAD_ORCHESTRATION_COMPLETE=0
  head_failure_guard() {
    local code=$?
    if [ "${code}" -ne 0 ] \
      && [ "${HEAD_ORCHESTRATION_COMPLETE}" != "1" ] \
      && [ "${BENCH_ON_LAUNCH_FAILURE}" = "1" ]; then
      echo "Head orchestration failed with exit_code=${code}; starting bench on ${NODES_FILE}" >&2
      run_bench_nodes start "${NODES_FILE}" "${NODE_INDICES}"
    fi
    exit "${code}"
  }
  trap head_failure_guard EXIT
  local head_addr=${HEAD_ADDRESS:-}
  [ -n "${head_addr}" ] || head_addr=$(hostname -I | tr ' ' '\n' | grep -m1 .)
  local head_http="http://$(http_host "${head_addr}"):${ENV_PORT}"
  local env_urls=("${head_http}")
  start_ray_head
  start_env_server
  wait_http "http://127.0.0.1:${ENV_PORT}/health"

  local node node_addr worker_script
  for node in $(read_nodes | tail -n +2); do
    if [ "${DRY_RUN}" = "1" ]; then
      node_addr="${node}"
    else
      node_addr=$(remote_first_ip "${node}")
    fi
    env_urls+=("http://$(http_host "${node_addr}"):${ENV_PORT}")
    worker_script=$(printf 'cd %q\nMLF_NAS_ROOT=%q MLF_LOCAL_ENVS=%q MLF_LOCAL_ROOT=%q SLIME_ENV=%q SSH_KEY=%q SSH_IPV6=%q bash scripts/utils/launch_agentic_training.sh --internal-role worker --resolved %q --head-address %q\n' \
      "${REPO_DIR}" "${MLF_NAS_ROOT}" "${MLF_LOCAL_ENVS}" "${MLF_LOCAL_ROOT}" "${SLIME_ENV}" "${SSH_KEY}" "${SSH_IPV6}" "${RESOLVED_CONFIG}" "${head_addr}")
    tmux_start_remote "${node}" mlf_multi_worker "${worker_script}" "${LOG_DIR}/multi_worker_$(safe_label "${node}").log"
  done
  for node in $(read_nodes | tail -n +2); do
    remote_wait_http "${node}" "http://127.0.0.1:${ENV_PORT}/health"
  done
  wait_ray_nodes "$(node_count)"

  local workers_csv
  workers_csv=$(IFS=,; echo "${env_urls[*]}")
  start_router "${workers_csv}"
  wait_http "http://127.0.0.1:${ROUTER_PORT}/health"
  start_train_driver "http://$(http_host "${head_addr}"):${ROUTER_PORT}"
  HEAD_ORCHESTRATION_COMPLETE=1
  trap - EXIT
}

