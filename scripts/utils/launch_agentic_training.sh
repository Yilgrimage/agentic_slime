ssh_node() {
  local host=$1
  local remote_cmd=$2
  local encoded wrapped
  local args=()
  [ "${SSH_IPV6}" = "1" ] && args+=("-6")
  args+=(
    "-n"
    "-o" "BatchMode=yes"
    "-o" "StrictHostKeyChecking=no"
    "-o" "UserKnownHostsFile=/dev/null"
    "-o" "GlobalKnownHostsFile=/dev/null"
    "-o" "CheckHostIP=no"
    "-o" "IdentitiesOnly=yes"
    "-i" "${SSH_KEY}"
    "-p" "${SSH_PORT}"
  )
  [ -z "${SSH_JUMP}" ] || args+=("-J" "${SSH_JUMP}")
  args+=("${SSH_USER}@${host}")
  encoded=$(printf '%s' "${remote_cmd}" | base64 | tr -d '\n')
  wrapped=$(printf "printf %%s '%s' | base64 -d | bash" "${encoded}")
  if [ "${DRY_RUN}" = "1" ]; then
    printf '+ ssh %s %q\n' "${host}" "${remote_cmd}"
    return 0
  fi
  ssh "${args[@]}" "${wrapped}"
}

remote_query() {
  local host=$1
  local cmd=$2
  local attempt
  for attempt in 1 2 3; do
    if ssh_node "${host}" "${cmd}"; then
      return 0
    fi
    echo "Retry ${attempt}/3 failed on ${host}" >&2
    sleep 5
  done
  return 1
}

